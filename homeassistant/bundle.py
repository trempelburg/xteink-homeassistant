"""Bundle Home Assistant: index.lua (tools/gamekit/gamekit.lua + src/draw.lua + src/ha.lua +
src/main.lua) and lockscreen.lua (src/ha.lua as `H`, src/draw.lua as `D` + src/lock/lock.lua: a lock
entry loads alone, without the app).

  python homeassistant/bundle.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'tools', 'gamekit'))
import bundle  # noqa: E402


def bundle_lock():
    ha = open(os.path.join(HERE, 'src', 'ha.lua'), encoding='utf-8').read().rstrip('\n')
    draw = open(os.path.join(HERE, 'src', 'draw.lua'), encoding='utf-8').read().rstrip('\n')
    lock = open(os.path.join(HERE, 'src', 'lock', 'lock.lua'), encoding='utf-8').read()
    text = ('-- GENERATED by homeassistant/bundle.py from src/ha.lua, src/draw.lua and src/lock/lock.lua\n'
            '-- -- edit those files, not this one.\n'
            'local H = (function()\n' + ha + '\nend)()\n\nlocal D = (function()\n' + draw + '\nend)()\n\n' + lock)
    out = os.path.join(HERE, 'lockscreen.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'homeassistant: lockscreen.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle.bundle(HERE)
    bundle_lock()
